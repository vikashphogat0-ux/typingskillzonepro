INSERT INTO exam_templates (slug,name,language,duration_sec,display_mode,backspace,scoring,description,is_active,category)
SELECT slug,name,language,600,'highlighted','full',
 jsonb_build_object('id',slug,'label',name,'unit','words','charsPerWord',5,'fullErrorWeight',1,'halfErrorWeight',0,'halfRules',jsonb_build_object('caseOnly',false,'punctuationOnly',false),'netMethod','penalty'),
 'Catalogue entry. Official duration, qualifying speed, error calculation, keyboard restrictions and display pattern must be verified against the applicable recruitment notification before exam-mode qualification is enabled.',
 true,category
FROM requested
ON CONFLICT (slug) DO UPDATE SET name=EXCLUDED.name, language=EXCLUDED.language, category=EXCLUDED.category,
 description=CASE WHEN exam_templates.description IS NULL OR exam_templates.description='' THEN EXCLUDED.description ELSE exam_templates.description END;
INSERT INTO exam_catalog_metadata(template_id,category,rule_status,keyboard_variant)
SELECT id,category,'needs_verification',
 CASE WHEN name ILIKE '%KrutiDev%' THEN 'KrutiDev'
      WHEN name ILIKE '%Inscript%' THEN 'Mangal Inscript'
      WHEN name ILIKE '%Remington Gail%' OR name ILIKE '%Gail%' THEN 'Remington Gail'
      WHEN name ILIKE '%Mangal%' THEN 'Mangal'
      WHEN name ILIKE '%Unicode%' THEN 'Unicode'
      ELSE NULL END
FROM exam_templates WHERE category IS NOT NULL
ON CONFLICT(template_id) DO UPDATE SET category=EXCLUDED.category, keyboard_variant=EXCLUDED.keyboard_variant;
